// Build one standalone SVG outline per county from MOI boundaries (via taiwan-atlas).
// Output: src/data/counties.js
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { feature } from "topojson-client";
import { geoMercator, geoPath, geoArea, geoCentroid, geoDistance } from "d3-geo";

const topo = JSON.parse(readFileSync(new URL("../node_modules/taiwan-atlas/counties-10t.json", import.meta.url)));
const fc = feature(topo, topo.objects.counties);

// Far-flung islands (東沙、太平島、釣魚臺 …) would shrink the main shape to a dot.
const MAX_KM = 120;
const EARTH_KM = 6371;

// Display names follow the CEC's 臺 spelling.
const name = (n) => n.replace(/^台/, "臺");

const out = {};
for (const f of fc.features) {
  const polys = f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates];
  const parts = polys.map((c) => ({ type: "Polygon", coordinates: c }));
  const main = parts.reduce((a, b) => (geoArea(a) > geoArea(b) ? a : b));
  const anchor = geoCentroid(main);
  const kept = parts.filter((p) => geoDistance(anchor, geoCentroid(p)) * EARTH_KM <= MAX_KM);
  const geom = { type: "MultiPolygon", coordinates: kept.map((p) => p.coordinates) };
  const proj = geoMercator().fitExtent([[4, 4], [96, 96]], geom);
  const d = geoPath(proj).digits(1)(geom);
  out[name(f.properties.COUNTYNAME)] = d;
  console.log(name(f.properties.COUNTYNAME), `${kept.length}/${parts.length} parts`, `${d.length} chars`);
}

mkdirSync(new URL("../src/data/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../src/data/counties.js", import.meta.url),
  "// Generated by scripts/build_maps.mjs — do not edit.\n" +
    "// Boundaries: 內政部國土測繪中心 直轄市、縣(市)界線, 政府資料開放授權條款第1版, via taiwan-atlas (MIT).\n" +
    `export const COUNTY_PATHS = ${JSON.stringify(out, null, 1)};\n`
);
